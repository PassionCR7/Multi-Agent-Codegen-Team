"""各 agent 的系统提示词。

提示词设计遵循三条原则：
    1. 角色单一职责 —— 每个 agent 只回答自己那一个问题。
    2. 强制事实约束 —— 必须基于工作区里的真实项目快照，禁止臆造。
    3. 结构化输出 —— 统一 JSON，便于程序解析与落盘。

注意每段提示词开头的 `[ROLE=XXX]` 标记：它是**机器可读**的角色标识，
供 MockLLM / 测试桩可靠地识别当前角色。不要用"在提示词里搜关键词"的方式
判断角色——BUGFIXER 的提示词里恰好含有 "aligner|security" 字样，会误判。
"""

from __future__ import annotations

import re

ROLE_MARKER_RE = re.compile(r"\[ROLE=([A-Z_]+)\]")


def detect_role(system_prompt: str) -> str | None:
    """从系统提示词中解析角色标记。"""
    m = ROLE_MARKER_RE.search(system_prompt or "")
    return m.group(1) if m else None


